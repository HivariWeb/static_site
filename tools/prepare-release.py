"""Refresh asset versions, security policy and an explicit deployment file list."""
from pathlib import Path
import re, hashlib, base64, json

ROOT = Path(__file__).resolve().parent.parent
# Keep the manifest and inline CSP hashes reproducible on Windows and Linux.
text_suffixes = {'.html', '.php', '.css', '.js', '.json', '.xml', '.txt', '.svg'}
text_files = [p for p in ROOT.iterdir() if p.is_file()]
for folder in ['assets', 'api', 'includes', 'config', 'tools']:
    text_files.extend((ROOT/folder).rglob('*'))
for file in text_files:
    if file.is_file() and (file.suffix in text_suffixes or file.name == '.htaccess'):
        data = file.read_bytes()
        if b'\r\n' in data:
            file.write_bytes(data.replace(b'\r\n', b'\n'))
versions = {name: hashlib.sha256((ROOT/name).read_bytes()).hexdigest()[:12]
            for name in ['style.css', 'script.js', 'site-config.js']}
for page in [*ROOT.glob('*.html'), *ROOT.glob('includes/templates/*.html')]:
    if '_snippet' in page.name:
        continue
    content = page.read_text('utf-8-sig')
    for name, version in versions.items():
        content = re.sub(r'(["\'])/?' + re.escape(name) + r'(?:\?v=[a-zA-Z0-9.\-]+)?(["\'])',
                         lambda m: m[1] + '/' + name + '?v=' + version + m[2], content)
    page.write_text(content.rstrip()+'\n', encoding='utf-8', newline='\n')
(ROOT/'config/assets.php').write_text("<?php\ndeclare(strict_types=1);\nreturn [\n"+
    ''.join(f"    '{name}' => '{value}',\n" for name,value in versions.items())+"];\n",encoding='utf-8',newline='\n')
home=(ROOT/'index.html').read_text('utf-8')
hashes=[]
for content in re.findall(r'<script\b[^>]*type=["\']application/ld\+json["\'][^>]*>(.*?)</script>',home,re.S):
    hashes.append("'sha256-"+base64.b64encode(hashlib.sha256(content.encode('utf-8')).digest()).decode('ascii')+"'")
csp="; ".join([
    "default-src 'self'", "base-uri 'self'", "object-src 'none'", "frame-ancestors 'none'",
    "form-action 'self'", "script-src 'self' https://mc.yandex.ru https://mc.yandex.com "+' '.join(hashes),
    "style-src 'self'", "font-src 'self'", "img-src 'self' data: https://*.yandex.ru https://*.yandex.com",
    "connect-src 'self' https://*.yandex.ru https://*.yandex.com", "frame-src 'none'"
])
headers={'X-Content-Type-Options':'nosniff','X-Frame-Options':'DENY',
         'Referrer-Policy':'strict-origin-when-cross-origin',
         'Permissions-Policy':'camera=(), microphone=(), geolocation=()',
         'Content-Security-Policy':csp}
(ROOT/'config/security.php').write_text("<?php\ndeclare(strict_types=1);\nreturn [\n"+
    ''.join("    "+repr(k)+" => '"+v.replace("'","\\'")+"',\n" for k,v in headers.items())+"];\n",encoding='utf-8',newline='\n')
htaccess='''# Generated by tools/prepare-release.py. Check proxy HTTPS behavior before release.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On
# Keep certificate renewal available.
RewriteRule ^\\.well-known/acme-challenge/ - [L]
# Never serve working files or server internals over HTTP.
RewriteRule (^|/)\\.(?!well-known(?:/|$)) - [F,L]
RewriteRule ^(?:includes|config|tools|tests|docs|audit-[^/]+|backups)(?:/|$) - [F,L,NC]
RewriteRule (?:_snippet\\.(?:html|js|css)|\\.docx|\\.credential\\.xml|\\.credentials\\.xml)$ - [F,L,NC]
# Redirect only safe navigation requests; never forward form bodies to another origin.
RewriteCond %{REQUEST_METHOD} ^(?:GET|HEAD)$
RewriteCond %{HTTP_HOST} !^www\\.dianaberezovskaya\\.online$ [NC]
RewriteRule ^ https://www.dianaberezovskaya.online%{REQUEST_URI} [R=301,L,NE]
RewriteCond %{REQUEST_METHOD} ^(?:GET|HEAD)$
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !^https$ [NC]
RewriteRule ^ https://www.dianaberezovskaya.online%{REQUEST_URI} [R=301,L,NE]
RewriteCond %{REQUEST_METHOD} ^(?:GET|HEAD)$
RewriteCond %{THE_REQUEST} \\s/+index\\.html(?:[?\\s]) [NC]
RewriteRule ^index\\.html$ https://www.dianaberezovskaya.online/ [R=301,L,NE]
</IfModule>

<IfModule mod_headers.c>
Header always unset X-Powered-By
'''
htaccess+=''.join('Header always set '+name+' "'+value+'"\n' for name,value in headers.items())
htaccess+='''<FilesMatch "\\.(?:html|xml|txt)$">
Header set Cache-Control "no-cache"
</FilesMatch>
</IfModule>
'''
(ROOT/'.htaccess').write_text(htaccess,encoding='utf-8',newline='\n')
files=['.htaccess','index.html','404.html','offer.html','privacy-policy.html','consent-personal-data.html',
       'consent-request.html','request.php','send-email.php','style.css','script.js','site-config.js','robots.txt','sitemap.xml']
for folder in ['assets','api','includes','config']:
    files += [p.relative_to(ROOT).as_posix() for p in (ROOT/folder).rglob('*')
              if p.is_file() and p.name not in ['hosting.example.php', 'deployment-manifest.json']]
files += ['tools/maintenance.php']
manifest={'release':'2026-10-23','files':[{'path':p,'sha256':hashlib.sha256((ROOT/p).read_bytes()).hexdigest()} for p in sorted(set(files))],
          'excluded':'Git metadata, audits, backups, tests, docs, private configuration, DOCX and legacy snippets',
          'requires_private_configuration':True,'requires_hosting_validation':True}
(ROOT/'config/deployment-manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
print(json.dumps({'asset_versions':versions,'deployment_files':len(files),'inline_script_hashes':len(hashes)}))
